function isAtOrDigitCode(cp) {
  let lo = 0, hi = RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < RANGES[mid][0]) hi = mid - 1; else if (cp > RANGES[mid][1]) lo = mid + 1; else return true;
  }
  return false;
}
// A character the search leaves out of words: in the list, or one this runtime itself reads as an at sign or a digit.
const isAtOrDigit = (ch) => isAtOrDigitCode(ch.codePointAt(0)) || /[@\p{Nd}]/u.test(ch) || /[@\p{Nd}]/u.test(ch.normalize('NFKC'));

module.exports = { RANGES, isAtOrDigitCode, isAtOrDigit };
