#!/usr/bin/env node
// Writes db/confusables.js from Unicode's UTS #39 confusables.txt: every single character (other than ASCII itself)
// whose confusable "prototype" is one ASCII letter or digit, mapped to that letter or digit in lower case. db/agents.js
// uses it for new agents' names (look-alike letters, and reserved names read through look-alikes).
//   node scripts/confusables.js <path to confusables.txt>
// The data file is not kept here; its version and date are written into the table's header, so a later update shows
// in review. Unicode's data files may be copied and used under the Unicode License v3 (https://www.unicode.org/terms_of_use.html).
'use strict';
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(process.argv[2], 'utf8');
const version = (src.match(/^# Version: (.+)$/m) || [])[1] || 'unknown';
const date = (src.match(/^# Date: (.+)$/m) || [])[1] || 'unknown';
const map = {};
for (const line of src.split('\n')) {
  const m = /^([0-9A-F]{4,6}) ;\t([0-9A-F ]+?) ;\t/.exec(line);
  if (!m || m[2].includes(' ')) continue;
  const from = String.fromCodePoint(parseInt(m[1], 16));
  const to = String.fromCodePoint(parseInt(m[2], 16));
  if (/^[\x00-\x7f]$/.test(from) || !/^[A-Za-z0-9]$/.test(to)) continue;
  map[from] = to.toLowerCase();
}
const keys = Object.keys(map).sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
const body = keys.map((k) => '\\u{' + k.codePointAt(0).toString(16) + '}' + map[k]).join('');
const out = `// Generated by scripts/confusables.js from Unicode's confusables.txt (UTS #39), version ${version}, dated ${date}.
// © Unicode, Inc., used under the Unicode License v3 (https://www.unicode.org/terms_of_use.html). Do not edit by hand.
// ${keys.length} characters, each written as an escape followed by the ASCII letter or digit (lower case) it reads as.
'use strict';
const PAIRS = '${body}';
const MAP = new Map();
for (const [, ch, to] of PAIRS.matchAll(/(\\P{M}\\p{M}*?|.)([a-z0-9])/gsu)) MAP.set(ch, to);
module.exports = { MAP, VERSION: '${version}' };
`;
fs.writeFileSync(path.join(__dirname, '..', 'db', 'confusables.js'), out);
console.log('wrote db/confusables.js:', keys.length, 'characters, Unicode', version);
