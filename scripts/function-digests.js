#!/usr/bin/env node
// Writes supabase/functions/<function>/source-digest.mjs for every Edge Function in the repository (R-3,
// harness/REVIEW-2026-10-26.md): the SHA-256 of each source file the function is built from, found by following its
// relative imports from index.ts, and one digest over them all. Each function returns that digest in the
// x-source-digest header of every answer, and the daily watch (.github/workflows/watch.yml) compares the deployed
// digest with main's. test/runner-alerts.test.js fails if any digest file is out of date.
//
// The digest is the SHA-256 of the lines "<sha256>  <path>\n", sorted by path, with paths from supabase/functions/,
// exactly as `sha256sum` prints them, so anyone can check it by hand:
//   cd supabase/functions && sha256sum <the files in SOURCE_FILES> | sort -k2 | sha256sum
// The digest file itself is not in the digest (it can't hold its own hash). What this proves, and what it doesn't:
// the deployed function was built from the source version whose digest file it carries. It does not prove that
// nobody changed the deployed code while keeping that digest file (RISKS.md RK91).
//
// Usage: node scripts/function-digests.js          (rewrite)
//        node scripts/function-digests.js --check  (exit 1 if out of date)
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..', 'supabase', 'functions');
const DIGEST_FILE = 'source-digest.mjs';
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

// Every function: a folder with an index.ts whose name doesn't start with "_" (_shared holds code, not a function).
function functions(root = ROOT) {
  return fs.readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('_') && fs.existsSync(path.join(root, d.name, 'index.ts')))
    .map((d) => d.name).sort();
}

// The relative imports of one file: static (import ... from "./x", export ... from "./x", import "./x") and dynamic
// (import("./x")). Package imports (npm:..., jsr:..., https:...) are versions pinned in the code, not files here.
function relativeImports(text) {
  const out = new Set();
  const patterns = [/\b(?:import|export)\s[^;]*?\bfrom\s*["']([^"']+)["']/g, /\bimport\s*["']([^"']+)["']/g, /\bimport\(\s*["']([^"']+)["']\s*\)/g];
  for (const re of patterns) for (const m of text.matchAll(re)) if (/^\.\.?\//.test(m[1])) out.add(m[1]);
  return [...out];
}

// The files a function is built from, as paths relative to supabase/functions, sorted.
function sources(name, root = ROOT) {
  const seen = new Set();
  const walk = (rel) => {
    if (seen.has(rel)) return;
    const abs = path.join(root, rel);
    if (!abs.startsWith(root + path.sep)) throw new Error(name + ': an import leaves supabase/functions: ' + rel);
    if (!fs.existsSync(abs)) throw new Error(name + ': imported file is missing: ' + rel);
    seen.add(rel);
    for (const spec of relativeImports(fs.readFileSync(abs, 'utf8'))) {
      const next = path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec));
      if (path.posix.basename(next) === DIGEST_FILE) continue;
      walk(next);
    }
  };
  walk(name + '/index.ts');
  return [...seen].sort();
}

function digestOf(name, root = ROOT) {
  const files = Object.fromEntries(sources(name, root).map((rel) => [rel, sha(fs.readFileSync(path.join(root, rel)))]));
  const lines = Object.entries(files).map(([rel, h]) => h + '  ' + rel + '\n').join('');
  return { files, digest: sha(lines) };
}

function render(name, root = ROOT) {
  const { files, digest } = digestOf(name, root);
  return [
    '// Generated by scripts/function-digests.js for the "' + name + '" Edge Function; do not edit (node scripts/function-digests.js',
    '// rewrites it, and test/runner-alerts.test.js fails if it is out of date). SOURCE_DIGEST is the SHA-256 of the',
    '// lines "<sha256>  <path>\\n" below, in this order, paths from supabase/functions/ (as sha256sum prints them). The',
    '// function returns it as x-source-digest (R-3); the daily watch compares it with main\'s.',
    'export const SOURCE_FILES = {',
    ...Object.entries(files).map(([rel, h]) => '  ' + JSON.stringify(rel) + ': ' + JSON.stringify(h) + ','),
    '};',
    'export const SOURCE_DIGEST = ' + JSON.stringify(digest) + ';',
    ''
  ].join('\n');
}

// { 'supabase/functions/<name>/source-digest.mjs': text } for every function.
function build(root = ROOT) {
  return Object.fromEntries(functions(root).map((n) => [path.join(path.relative(path.join(__dirname, '..'), root), n, DIGEST_FILE), render(n, root)]));
}

if (require.main === module) {
  const want = build();
  const repo = path.join(__dirname, '..');
  if (process.argv.includes('--check')) {
    const stale = Object.entries(want).filter(([f, text]) => !fs.existsSync(path.join(repo, f)) || fs.readFileSync(path.join(repo, f), 'utf8') !== text);
    if (stale.length) { console.error('out of date (run node scripts/function-digests.js): ' + stale.map(([f]) => f).join(', ')); process.exit(1); }
  } else {
    for (const [f, text] of Object.entries(want)) fs.writeFileSync(path.join(repo, f), text);
    console.log('wrote ' + Object.keys(want).join(', '));
  }
}

module.exports = { build, functions, sources, digestOf, relativeImports, DIGEST_FILE, ROOT };
